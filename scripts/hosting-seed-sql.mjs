// Writes supabase/migrations/20261026120000_pg1_hosting.sql from the curated
// dataset (lib/hosting/dataset.mjs), so the seed and the bundled fallback are
// the same rows. tests/hosting.test.mjs checks the committed file matches.
// Usage: node scripts/hosting-seed-sql.mjs
import { writeFileSync } from 'node:fs';
import { JURISDICTIONS, PROVIDERS } from '../lib/hosting/dataset.mjs';

export const HOSTING_MIGRATION = new URL('../supabase/migrations/20261026120000_pg1_hosting.sql', import.meta.url);

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const j = (v) => `${q(JSON.stringify(v))}::jsonb`;

export function hostingMigrationSql() {
  const lines = [
    '-- hosting_advisor (lib/hosting): PG1\'s curated hosting dataset.',
    '--',
    '--   pg1_jurisdictions  one row per jurisdiction: data-protection regime, EU',
    '--                      transfer status, published government data-access',
    '--                      frameworks, sanctions status. Every fact is',
    '--                      { value, source_url, checked_on, verified }.',
    '--   pg1_providers      one row per provider: headquarters, US parent, cost',
    '--                      tier, regions, compute SLA, acceptable use policy, DPA.',
    '--',
    '-- Public, factual information from official sources; no personal data.',
    '-- The seed rows are marked verified: false until the operator confirms each',
    '-- one (/hosting confirm) or an approved lab update replaces it.',
    '-- Generated by scripts/hosting-seed-sql.mjs from lib/hosting/dataset.mjs.',
    '--',
    '-- Service role only: RLS on, nothing for anon/authenticated.',
    '-- NOT APPLIED AUTOMATICALLY. Safe to run more than once (the seed inserts',
    '-- skip rows that exist, so later updates are kept). Deletes no data.',
    '',
    'create table if not exists public.pg1_jurisdictions (',
    '  code text primary key,',
    '  name text not null,',
    '  region text not null,',
    '  eea boolean not null default false,',
    '  data_protection jsonb not null,',
    '  eu_adequacy jsonb not null,',
    '  government_access jsonb not null default \'[]\'::jsonb,',
    '  sanctions jsonb not null,',
    '  updated_at timestamptz not null default now()',
    ');',
    '',
    'create table if not exists public.pg1_providers (',
    '  id text primary key,',
    '  name text not null,',
    '  hq text not null,',
    '  us_parent boolean not null,',
    '  cost_tier text not null check (cost_tier in (\'low\', \'medium\', \'high\')),',
    '  regions jsonb not null,',
    '  sla jsonb not null,',
    '  aup jsonb not null,',
    '  dpa jsonb not null,',
    '  updated_at timestamptz not null default now()',
    ');',
    ''
  ];
  for (const r of JURISDICTIONS) {
    lines.push(`insert into public.pg1_jurisdictions (code, name, region, eea, data_protection, eu_adequacy, government_access, sanctions) values (${q(r.code)}, ${q(r.name)}, ${q(r.region)}, ${r.eea}, ${j(r.data_protection)}, ${j(r.eu_adequacy)}, ${j(r.government_access)}, ${j(r.sanctions)}) on conflict (code) do nothing;`);
  }
  lines.push('');
  for (const p of PROVIDERS) {
    lines.push(`insert into public.pg1_providers (id, name, hq, us_parent, cost_tier, regions, sla, aup, dpa) values (${q(p.id)}, ${q(p.name)}, ${q(p.hq)}, ${p.us_parent}, ${q(p.cost_tier)}, ${j(p.regions)}, ${j(p.sla)}, ${j(p.aup)}, ${j(p.dpa)}) on conflict (id) do nothing;`);
  }
  lines.push('', 'alter table public.pg1_jurisdictions enable row level security;', 'alter table public.pg1_providers enable row level security;', 'revoke all on public.pg1_jurisdictions from public, anon, authenticated;', 'revoke all on public.pg1_providers from public, anon, authenticated;', '', "notify pgrst, 'reload schema';", '');
  return lines.join('\n');
}

if (process.argv[1] && import.meta.url.endsWith(process.argv[1].split('/').pop())) {
  writeFileSync(HOSTING_MIGRATION, hostingMigrationSql());
  console.log('wrote', HOSTING_MIGRATION.pathname);
}
